const herodotImportPath = "github.com/ory/herodot/v2"

const generatedHeader = "Code generated by protoc-gen-herodot. DO NOT EDIT."

// fileHeader copies the comments before the proto file's syntax statement,
// such as a license header, as protoc-gen-go does.
func fileHeader(g *protogen.GeneratedFile, f *protogen.File) {
	syntax := f.Desc.SourceLocations().ByPath(protoreflect.SourcePath{fileSyntaxField})
	for _, c := range syntax.LeadingDetachedComments {
		for _, line := range strings.Split(strings.TrimSuffix(c, "\n"), "\n") {
			g.P("//", line)
		}
		g.P()
	}
}

// fileSyntaxField is the field number of FileDescriptorProto.syntax.
const fileSyntaxField = 12

func generateGo(gen *protogen.Plugin, cf *catalogFile) {
	f := cf.file
	g := gen.NewGeneratedFile(f.GeneratedFilenamePrefix+".herodot.go", f.GoImportPath)
	fileHeader(g, f)
	g.P("// ", generatedHeader)
	g.P("// source: ", f.Desc.Path())
	g.P()
	g.P("package ", f.GoPackageName)
	g.P()
	// protogen would name the import after the last path element, "v2".
	g.P("import herodot ", strconv.Quote(herodotImportPath))
	g.P()

	for _, ce := range cf.enums {
		g.P("// Reasons of ", ce.enum.Desc.FullName(), " in domain ", ce.domain, ".")
		g.P("var (")
		for i, r := range ce.reasons {
			if i > 0 {
				g.P()
			}
			g.P("// ", r.goName(), " is ", r.domain, "/", r.name, " (", r.code.name, ").")
			if r.comment != "" {
				g.P("//")
				for _, l := range strings.Split(r.comment, "\n") {
					g.P(strings.TrimRight("// "+l, " "))
				}
			}
			if len(r.metadataKeys) > 0 {
				g.P("//")
				g.P("// Metadata keys: ", strings.Join(r.metadataKeys, ", "), ".")
			}
			if r.deprecated {
				g.P("//")
				g.P("// Deprecated: do not raise this reason in new code.")
			}
			g.P(r.goName(), " = herodot.Define(",
				strconv.Quote(r.domain), ", ", strconv.Quote(r.name), ", ",
				"herodot.", r.code.goName(), ", ",
				strconv.Quote(r.message), ")")
		}
		g.P(")")
		g.P()
	}
}

// reasonJSON is the representation of a reason in the JSON catalog.
type reasonJSON struct {
	Domain        string   `json:"domain"`
	Reason        string   `json:"reason"`
	Code          string   `json:"code"`
	CanonicalCode string   `json:"canonicalCode"`
	HTTPStatus    uint32   `json:"httpStatus"`
	Message       string   `json:"message"`
	MetadataKeys  []string `json:"metadataKeys"`
	Description   string   `json:"description,omitempty"`
	Deprecated    bool     `json:"deprecated,omitempty"`
}

func toJSON(r *reason) reasonJSON {
	keys := r.metadataKeys
	if keys == nil {
		keys = []string{}
	}
	return reasonJSON{
		Domain:        r.domain,
		Reason:        r.name,
		Code:          r.code.name,
		CanonicalCode: r.code.canonical.name,
		HTTPStatus:    r.code.httpStatus,
		Message:       r.message,
		MetadataKeys:  keys,
		Description:   r.comment,
		Deprecated:    r.deprecated,
	}
}

func generateJSON(gen *protogen.Plugin, d *domain) error {
	out := struct {
		Domain  string       `json:"domain"`
		Reasons []reasonJSON `json:"reasons"`
	}{Domain: d.name}
	for _, r := range d.reasons {
		out.Reasons = append(out.Reasons, toJSON(r))
	}
	b, err := json.MarshalIndent(out, "", "  ")
	if err != nil {
		return err
	}
	g := gen.NewGeneratedFile(d.name+".errors.json", "")
	_, _ = g.Write(append(b, '\n'))
	return nil
}

func generateTS(gen *protogen.Plugin, d *domain) {
	g := gen.NewGeneratedFile(d.name+".errors.ts", "")
	g.P("// ", generatedHeader)
	g.P()
	g.P("export const domain = ", strconv.Quote(d.name), " as const")
	g.P()
	g.P("export const Reason = {")
	for _, r := range d.reasons {
		if r.deprecated {
			g.P("  /** @deprecated */")
		}
		g.P("  ", r.name, ": ", strconv.Quote(r.name), ",")
	}
	g.P("} as const")
	g.P()
	g.P("export type Reason = (typeof Reason)[keyof typeof Reason]")
	g.P()
	g.P("export interface Definition {")
	g.P("  readonly domain: typeof domain")
	g.P("  readonly reason: Reason")
	g.P("  readonly code: string")
	g.P("  readonly canonicalCode: string")
	g.P("  readonly httpStatus: number")
	g.P("  readonly message: string")
	g.P("  readonly metadataKeys: readonly string[]")
	g.P("}")
	g.P()
	g.P("export const definitions: { readonly [R in Reason]: Definition } = {")
	for _, r := range d.reasons {
		j := toJSON(r)
		keys := make([]string, len(j.MetadataKeys))
		for i, k := range j.MetadataKeys {
			keys[i] = strconv.Quote(k)
		}
		if r.comment != "" {
			g.P("  /**")
			for _, l := range strings.Split(r.comment, "\n") {
				g.P(strings.TrimRight("   * "+strings.ReplaceAll(l, "*/", "*\\/"), " "))
			}
			g.P("   */")
		}
		g.P("  ", r.name, ": {")
		g.P("    domain,")
		g.P("    reason: Reason.", r.name, ",")
		g.P("    code: ", strconv.Quote(j.Code), ",")
		g.P("    canonicalCode: ", strconv.Quote(j.CanonicalCode), ",")
		g.P("    httpStatus: ", j.HTTPStatus, ",")
		g.P("    message: ", strconv.Quote(j.Message), ",")
		g.P("    metadataKeys: [", strings.Join(keys, ", "), "],")
		g.P("  },")
	}
	g.P("}")
}

func generateMarkdown(gen *protogen.Plugin, d *domain) {
	g := gen.NewGeneratedFile(d.name+".md", "")
	g.P("<!-- ", generatedHeader, " -->")
	g.P()
	g.P("# Errors of `", d.name, "`")
	g.P()
	g.P("| Reason | Code | gRPC code | HTTP status | Message |")
	g.P("| --- | --- | --- | --- | --- |")
	for _, r := range d.reasons {
		name := "[`" + r.name + "`](#" + strings.ToLower(r.name) + ")"
		if r.deprecated {
			name += " (deprecated)"
		}
		g.P("| ", name, " | `", r.code.name, "` | `", r.code.canonical.name, "` | ", r.code.httpStatus, " | ", mdCell(r.message), " |")
	}
	for _, r := range d.reasons {
		g.P()
		g.P("## ", r.name)
		g.P()
		if r.deprecated {
			g.P("**Deprecated.** Clients should still handle this reason, but new code doesn't raise it.")
			g.P()
		}
		if r.comment != "" {
			g.P(r.comment)
			g.P()
		}
		g.P("- Code: `", r.code.name, "` (gRPC `", r.code.canonical.name, "`, HTTP ", r.code.httpStatus, ")")
		g.P("- Message: ", r.message)
		if len(r.metadataKeys) > 0 {
			g.P("- Metadata keys: `", strings.Join(r.metadataKeys, "`, `"), "`")
		}
	}
}

func mdCell(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, "|", `\|`), "\n", " ")
}

func generateOpenAPI(gen *protogen.Plugin, d *domain) error {
	schema := map[string]any{
		"title":       fmt.Sprintf("Reasons of %s", d.name),
		"description": fmt.Sprintf("The values of ErrorInfo.reason when ErrorInfo.domain is %q.", d.name),
		"type":        "string",
	}
	var enum []string
	for _, r := range d.reasons {
		enum = append(enum, r.name)
	}
	schema["enum"] = enum
	b, err := json.MarshalIndent(schema, "", "  ")
	if err != nil {
		return err
	}
	g := gen.NewGeneratedFile(d.name+".openapi.json", "")
	_, _ = g.Write(append(b, '\n'))
	return nil
}
